# FIND TEST ENCOUNTER
# ============================================================

def find_valid_test_encounter(
    limit=500
):
    """
    Find an encounter that can pass through E1 and E2.
    """

    from ML.treatment_advisor.candidate_treatments import (
        generate_candidates_for_encounter
    )

    engine = get_database_engine()

    query = f"""
        SELECT
            encounter_id
        FROM patient_encounter
        WHERE recovery_days IS NOT NULL
        ORDER BY visit_timestamp
        LIMIT {int(limit)}
    """

    encounters = pd.read_sql(
        query,
        engine
    )

    if encounters.empty:

        raise RuntimeError(
            "No test encounters found."
        )

    last_error = None

    for encounter_id in encounters[
        "encounter_id"
    ].tolist():

        try:

            (
                context,
                candidates,
                candidate_records
            ) = generate_candidates_for_encounter(
                encounter_id
            )

            if (
                context is None
                or candidates is None
                or candidates.empty
            ):

                continue

            return (
                encounter_id,
                context,
                candidates
            )

        except Exception as e:

            last_error = e
            continue

    if last_error is not None:

        raise RuntimeError(
            "Could not find a valid E11 test encounter. "
            f"Last encountered error: {last_error}"
        )

    raise RuntimeError(
        "Could not find a valid E11 test encounter."
    )


