# ============================================================
# LOAD E6 MODEL
# ============================================================

def load_e6_model():

    if not E6_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"E6 model artifact not found: {E6_MODEL_PATH}"
        )

    artifact = joblib.load(
        E6_MODEL_PATH
    )

    if not isinstance(artifact, dict):
        raise ValueError(
            "Invalid E6 model artifact."
        )

    if "model" not in artifact:
        raise ValueError(
            "E6 artifact missing 'model'."
        )

    if "feature_names" not in artifact:
        raise ValueError(
            "E6 artifact missing 'feature_names'."
        )

    return (
        artifact["model"],
        artifact["feature_names"]
    )


# ============================================================
# FEATURE CONSTRUCTION
# ============================================================

def build_prediction_features(
    patient_context,
    treatment_id,
    feature_names
):
    """
    Construct exactly the same feature representation used
    by E6 for inference.
    """

    row = {}

    # --------------------------------------------------------
    # Numerical features
    # --------------------------------------------------------

    row["age"] = patient_context.get(
        "age",
        0
    )

    vitals = patient_context.get(
        "vitals",
        {}
    )

    row["temperature"] = vitals.get(
        "temperature",
        0
    )

    row["heart_rate"] = vitals.get(
        "heart_rate",
        0
    )

    row["respiratory_rate"] = vitals.get(
        "respiratory_rate",
        0
    )

    row["systolic_bp"] = vitals.get(
        "systolic_bp",
        0
    )

    row["diastolic_bp"] = vitals.get(
        "diastolic_bp",
        0
    )

    row["spo2"] = vitals.get(
        "spo2",
        0
    )

    # --------------------------------------------------------
    # Categorical features
    # --------------------------------------------------------

    row["gender"] = str(
        patient_context.get(
            "gender",
            "UNKNOWN"
        )
    )

    row["disease_id"] = str(
        patient_context.get(
            "disease_id",
            "UNKNOWN"
        )
    )

    row["severity_id"] = str(
        patient_context.get(
            "severity_id",
            "UNKNOWN"
        )
    )

    row["treatment_id"] = str(
        treatment_id
    )

    # --------------------------------------------------------
    # Symptoms
    # --------------------------------------------------------

    symptom_vector = patient_context.get(
        "symptom_vector",
        {}
    )

    for symptom_name, value in symptom_vector.items():

        row[symptom_name] = value

    X = pd.DataFrame(
        [row]
    )

    # --------------------------------------------------------
    # Same encoding as E6
    # --------------------------------------------------------

    categorical_columns = [
        "gender",
        "disease_id",
        "severity_id",
        "treatment_id"
    ]

    X = pd.get_dummies(
        X,
        columns=[
            c
            for c in categorical_columns
            if c in X.columns
        ],
        dtype=float
    )

    # --------------------------------------------------------
    # Exact E6 feature alignment
    # --------------------------------------------------------

    X = X.reindex(
        columns=feature_names,
        fill_value=0
    )

    X = X.fillna(0)

    return X


# ============================================================
# SHAP EXPLAINER
# ============================================================

def create_explainer(model):
    """
    Create a TreeExplainer for the E6 Random Forest.
    """

    return shap.TreeExplainer(
        model
    )


# ============================================================
# EXTRACT POSITIVE-CLASS SHAP VALUES
# ============================================================

def get_positive_class_shap_values(
    explainer,
    X
):
    """
    Obtain SHAP values corresponding to the treatment-success
    / positive class.

    SHAP versions may return either:
        - list[class][sample][feature]
        - ndarray[sample][feature]
        - ndarray[sample][feature][class]

    This function normalizes those formats.
    """

    shap_values = explainer.shap_values(
        X
    )

    # --------------------------------------------------------
    # Older SHAP format:
    #
    # list:
    #     class 0 -> samples x features
    #     class 1 -> samples x features
    # --------------------------------------------------------

    if isinstance(
        shap_values,
        list
    ):

        if len(shap_values) < 2:

            raise ValueError(
                "Expected SHAP values for two classes."
            )

        return np.asarray(
            shap_values[1]
        )

    shap_values = np.asarray(
        shap_values
    )

    # --------------------------------------------------------
    # Newer SHAP format:
    #
    # samples x features x classes
    # --------------------------------------------------------

    if shap_values.ndim == 3:

        if shap_values.shape[2] >= 2:

            return shap_values[
                :,
                :,
                1
            ]

    # --------------------------------------------------------
    # Binary matrix:
    #
    # samples x features
    # --------------------------------------------------------

    if shap_values.ndim == 2:

        return shap_values

    raise ValueError(
        "Unsupported SHAP output shape: "
        f"{shap_values.shape}"
    )


# ============================================================
# EXPLAIN ONE TREATMENT
# ============================================================

def explain_treatment(
    patient_context,
    treatment_id,
    top_n=TOP_FEATURES
):
    """
    Generate SHAP explanation for one patient-treatment pair.
    """

    model, feature_names = load_e6_model()

    X = build_prediction_features(
        patient_context,
        treatment_id,
        feature_names
    )

    # --------------------------------------------------------
    # Model probability
    # --------------------------------------------------------

    model_probability = float(
        model.predict_proba(
            X
        )[0][1]
    )

    # --------------------------------------------------------
    # SHAP
    # --------------------------------------------------------

    explainer = create_explainer(
        model
    )

    shap_values = get_positive_class_shap_values(
        explainer,
        X
    )

    values = shap_values[0]

    # --------------------------------------------------------
    # Base value
    # --------------------------------------------------------

    expected_value = explainer.expected_value

    if isinstance(
        expected_value,
        (list, np.ndarray)
    ):

        expected_value = np.asarray(
            expected_value
        ).flatten()

        if len(expected_value) >= 2:

            base_value = float(
                expected_value[1]
            )

        else:

            base_value = float(
                expected_value[0]
            )

    else:

        base_value = float(
            expected_value
        )

    # --------------------------------------------------------
    # Feature contribution table
    # --------------------------------------------------------

    explanation_df = pd.DataFrame({
        "feature": feature_names,
        "feature_value": X.iloc[0].values,
        "shap_value": values
    })

    explanation_df[
        "absolute_shap_value"
    ] = explanation_df[
        "shap_value"
    ].abs()

    explanation_df = (
        explanation_df
        .sort_values(
            "absolute_shap_value",
            ascending=False
        )
        .reset_index(
            drop=True
        )
    )

    # --------------------------------------------------------
    # Top features
    # --------------------------------------------------------

    top_features = []

    for _, row in explanation_df.head(
        top_n
    ).iterrows():

        direction = (
            "INCREASES"
            if row["shap_value"] > 0
            else "DECREASES"
        )

        top_features.append({
            "feature": str(
                row["feature"]
            ),
            "feature_value": float(
                row["feature_value"]
            ),
            "shap_value": float(
                row["shap_value"]
            ),
            "absolute_shap_value": float(
                row["absolute_shap_value"]
            ),
            "direction": direction
        })

    return {
        "treatment_id": treatment_id,
        "model_type": (
            "Random Forest Classifier"
        ),
        "model_success_probability": (
            model_probability
        ),
        "base_value": base_value,
        "top_features": top_features,
        "explanation_method": (
            "SHAP TreeExplainer"
        ),
        "interpretation": (
            "SHAP values explain model feature "
            "contributions and do not establish causality "
            "or clinical treatment effectiveness."
        )
    }


# ============================================================
# EXPLAIN MULTIPLE TREATMENTS
# ============================================================

def explain_treatments(
    patient_context,
    treatment_ids,
    top_n=TOP_FEATURES
):
    """
    Generate SHAP explanations for multiple treatments.
    """

    results = []

    for treatment_id in treatment_ids:

        results.append(
            explain_treatment(
                patient_context,
                treatment_id,
                top_n=top_n
            )
        )

    return results


# ============================================================
# VALIDATE SHAP EXPLANATION
# ============================================================

def validate_explanation(
    explanation
):
    """
    Validate the E11 explanation structure.
    """

    required_fields = [
        "treatment_id",
        "model_type",
        "model_success_probability",
        "base_value",
        "top_features",
        "explanation_method",
        "interpretation"
    ]

    for field in required_fields:

        if field not in explanation:

            raise RuntimeError(
                "E11 explanation missing field: "
                f"{field}"
            )

    probability = explanation[
        "model_success_probability"
    ]

    if not np.isfinite(
        probability
    ):

        raise RuntimeError(
            "E11 produced a non-finite probability."
        )

    if not (
        0 <= probability <= 1
    ):

        raise RuntimeError(
            "E11 probability is outside [0, 1]."
        )

    if not isinstance(
        explanation["top_features"],
        list
    ):

        raise RuntimeError(
            "E11 top_features must be a list."
        )

    for feature in explanation[
        "top_features"
    ]:

        required_feature_fields = [
            "feature",
            "feature_value",
            "shap_value",
            "absolute_shap_value",
            "direction"
        ]

        for field in required_feature_fields:

            if field not in feature:

                raise RuntimeError(
                    "E11 feature explanation missing: "
                    f"{field}"
                )

        if feature[
            "direction"
        ] not in {
            "INCREASES",
            "DECREASES"
        }:

            raise RuntimeError(
                "Invalid SHAP direction."
            )


