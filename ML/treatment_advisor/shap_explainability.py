"""
E11 - SHAP Explainability

Purpose
-------
Explain treatment-success predictions generated by the E6
Random Forest classifier.

E11 does NOT train a new predictive model.

It loads:
    E6 - treatment_success_model.pkl

and generates SHAP feature contributions for individual
patient-treatment predictions.

Important interpretation
------------------------
SHAP values describe how features contribute to the model's
prediction.

They do NOT establish:
    - causality
    - treatment effectiveness
    - clinical risk
    - medical necessity
    - prescribing recommendations

The explanation is therefore a model-interpretability output.
"""


